/**
 * DTO 검증에 공유하는 형식 패턴.
 *
 * 시간·날짜 문자열은 여러 모듈이 각자 정규식을 들고 있으면 느슨한 쪽이 통로가 된다.
 * 실제로 "banana" 같은 값이 취향 프로필에 저장돼 일정 생성을 막은 적이 있어,
 * 자릿수만 세지 말고 실재하는 시각·날짜인지까지 본다.
 */

/** "HH:mm" (00:00~23:59). \d{2}:\d{2} 는 "99:99" 를 통과시키므로 쓰지 않는다. */
export const HH_MM = /^([01]\d|2[0-3]):[0-5]\d$/;

/** "YYYY-MM-DD" */
export const YYYY_MM_DD = /^\d{4}-(0[1-9]|1[0-2])-(0[1-9]|[12]\d|3[01])$/;
