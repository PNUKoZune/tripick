/**
 * DTO 검증에 공유하는 형식 패턴.
 *
 * 시간·날짜 문자열은 여러 모듈이 각자 정규식을 들고 있으면 느슨한 쪽이 통로가 된다.
 * 실제로 "banana" 같은 값이 취향 프로필에 저장돼 일정 생성을 막은 적이 있어,
 * 자릿수만 세지 말고 실재하는 시각·날짜인지까지 본다.
 */

/** "HH:mm" (00:00~23:59). \d{2}:\d{2} 는 "99:99" 를 통과시키므로 쓰지 않는다. */
export const HH_MM = /^([01]\d|2[0-3]):[0-5]\d$/;

/** "YYYY-MM-DD" */
export const YYYY_MM_DD = /^\d{4}-(0[1-9]|1[0-2])-(0[1-9]|[12]\d|3[01])$/;

/**
 * 저장/취향 사진 URL. 절대 URL(라이브 R2) 과 상대경로(로컬·웹뷰 `/storage` 프록시) 를 모두 받는다.
 * STORAGE_PUBLIC_URL 이 `/storage` 상대경로로 바뀌면서 `@IsUrl`(절대 URL) 은 통과 못 한다.
 * 남용은 서버가 "본인 photoUrls 목록에 있는 값인지" 로 따로 막으므로 형식만 느슨히 본다.
 */
export const STORAGE_URL = /^(https?:\/\/\S+|\/\S+)$/;

/**
 * 비공개 스토리지 키(취향 사진). `preferences/<userId>/<timestamp>-<index>.<ext>` 형태.
 *
 * URL 이 아니라 키인 이유: 표시용 URL 이 만료되는 서명 URL 로 바뀌어 식별자로 쓸 수 없다.
 * 앞의 `/` 를 허용하지 않고 `..` 를 막는다 — 남용은 서버가 "본인 키 목록에 있는지" 로 따로
 * 막으므로 여기서는 형태만 본다.
 */
export const STORAGE_KEY = /^(?!.*\.\.)[A-Za-z0-9][A-Za-z0-9._\-/]{0,254}$/;
